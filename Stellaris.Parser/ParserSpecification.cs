 *
 * 术语定义
 * --------
 * 规范中使用的术语定义如下，贯穿全文：
 *
 * - 根目录（Root Directory）：模组文件系统的顶层目录路径。解析器按
 *   添加顺序维护一个根目录列表，列表末尾（索引最大）的目录优先级最高。
 *
 * - 相对路径（Relative Path）：相对于某个根目录的路径，使用正斜杠 '/'
 *   作为目录分隔符，不以 '/' 开头。
 *
 * - 优先级（Priority）：根目录在列表中的索引值，索引越大优先级越高。
 *   在文件查找、常量合并、本地化覆盖等场景中，高优先级条目覆盖
 *   低优先级条目。
 *
 * - 逻辑值（Logical Value）：存储在 AstNode.Value 中的对象，代表节点
 *   经过解析和求值后的运行时数据。对于 Simple 节点，此值可为 int、
 *   float、string、ConstantValue 等类型。
 *
 * - 原始文本（Raw Text）：存储在 AstNode.RawText 中的字符串，代表节点
 *   在源文件中对应的原始字符序列，未经任何求值或格式化。
 *
 * - 常量引用（Constant Reference）：一个 Simple 节点在其逻辑值或原始
 *   文本中依赖某个全局常量或局部常量的关系。
 *
 * - 常量引用索引（Constant Reference Index）：维护全局常量名称到
 *   所有引用该常量的 AST 节点集合的映射关系的数据结构。
 *
 *
 * 总体执行顺序（强制，不可调整）
 * ------------------------------
 * 整个解析器生命周期分为六个核心阶段，执行顺序严格如下。
 * 任何实现若调整阶段顺序，均视为对本规范的违反。
 *
 * 阶段 0（系统初始化）：
 *   建立根目录优先级列表，初始化日志系统，创建空的全局常量表，
 *   创建空的常量引用索引。
 *
 * 阶段 1（扫描与加载）：
 *   文件发现 → 词法分析 → 语法分析 → AST 构建（含 RawText 填充）
 *   → 全局常量收集 → 局部常量收集 → CSV 合并 → 本地化加载。
 *
 * 阶段 2（内联脚本展开）：
 *   递归展开所有 inline_script 节点，展开过程中新产生的节点
 *   必须继承 RawText 元数据。
 *
 * 阶段 3（常量解析与求值）：
 *   构建局部常量表 → 构建常量引用索引 → 遍历 AST 执行 @var 和
 *   @[expr] 求值 → 将求值结果写入 AstNode.Value。
 *
 * 阶段 4（CRUD 内存操作与索引维护）：
 *   上层通过适配器接口增删改 AST 节点时，同步维护常量引用索引。
 *
 * 阶段 5（序列化与写回）：
 *   根据 AstNode.RawText 和 AstNode.Value 的优先级规则生成输出
 *   文本，执行原子写入。
 *
 *
 * 第一章：核心数据结构定义（AST 节点）
 * ====================================
 *
 * 1.1 节点类型枚举（NodeType）
 *     定义 AST 节点的分类，解析器必须严格区分以下类型：
 *
 *     - Simple     ：键值对中的值部分为简单类型（数字、字符串、
 *                    常量引用、未加引号字符串）。这是唯一包含
 *                    Value 和 RawText 的节点类型。
 *     - Block      ：包含一组键值对的容器，子节点按顺序排列。
 *     - List       ：包含一组无键简单值的容器，所有子节点的
 *                    Key 必须为 null。
 *     - Comment    ：注释节点，独立存储但通过 AssociatedComments
 *                    关联到所属的语句节点。
 *     - Error      ：解析错误的占位节点，序列化时被丢弃。
 *     - InlineScript：特殊块类型，表示内联脚本容器。
 *       注意：通用解析器**不产生**该类型（内联脚本块在解析产物中为普通
 *       Block）；该类型仅由引擎层（ScriptExpander）按黑箱游戏引擎唯一
 *       支持的内联键名 "inline_script" 识别/标记，并用于展开与序列化。
 *
 * 1.2 节点类（AstNode）
 *     以下是 AstNode 类的完整字段定义。所有字段必须在节点创建时
 *     正确初始化，任何字段的缺失均视为实现缺陷。
 *
 *     ---- 基础标识字段 ----
 *
 *     Type (NodeType)
 *         节点的类型标识。决定节点在序列化和遍历时的行为。
 *
 *     Key (string?)
 *         节点的键。对于 Block 和 Simple 节点，此字段非空。
 *         对于 List 和 Comment 节点，此字段为 null。
 *         键的有效字符由词法分析器定义（见第二章）。
 *
 *     Value (object?)
 *         节点的逻辑值。仅对 Simple 类型节点有效。
 *         在阶段 1（解析）中，此字段存储词法分析器识别的原始值
 *         （如 int、string、ConstantValue）。
 *         在阶段 3（求值）中，此字段被更新为常量替换或表达式
 *         计算后的最终结果。
 *         对于非 Simple 类型节点，此字段必须为 null。
 *
 *     Children (List<AstNode>)
 *         子节点列表。仅对 Block、List、InlineScript 有效。
 *         对于 Simple 和 Comment 节点，此列表为空。
 *         子节点顺序反映源文件中的出现顺序。
 *
 *     ---- 元数据字段 ----
 *
 *     IsQuoted (bool)
 *         指示该节点的值在源文件中是否被双引号包围。
 *         仅对 Simple 节点有效。此字段影响序列化时的引号输出
 *         决策（见第七章）。
 *
 *     StartLine (int)
 *         节点在源文件中的起始行号，从 1 开始计数。
 *
 *     EndLine (int)
 *         节点在源文件中的结束行号，从 1 开始计数。
 *
 *     StartColumn (int)
 *         节点在源文件中的起始列号，从 1 开始计数。
 *         制表符按 1 个字符计列号。
 *
 *     EndColumn (int)
 *         节点在源文件中的结束列号，从 1 开始计数。
 *
 *     AssociatedComments (List<AstNode>)
 *         与此节点关联的注释节点列表。注释节点不属于 Children，
 *         而是通过此列表独立关联，以支持注释位置的精确恢复。
 *
 *     IndentWidth (int)
 *         节点内容的缩进宽度。用于序列化时的缩进计算。
 *         制表符按 4 个空格计算缩进宽度。
 *
 *     OriginalLayout (OriginalLayout)
 *         指示节点的原始布局（单行/多行/未知）。
 *         用于序列化时的换行决策（见第七章）。
 *
 *     SeparatorType (TokenType?)
 *         节点使用的分隔符类型（=、>、<、>=、<=）。
 *         仅对 Simple 节点有效。默认为 '='。
 *
 *     ---- 核心元数据字段：原始文本 ----
 *
 *     RawText (string?)
 *         节点在源文件中的原始文本表示，未经任何求值或格式化。
 *
 *         此字段的适用规则：
 *         - 仅对 Simple 类型节点有效。对于 Block、List、
 *           InlineScript、Comment、Error 类型节点，此字段必须
 *           为 null。
 *         - 此字段存储的是词法分析器在源文件中匹配到的完整
 *           标记序列的字符内容。
 *
 *         此字段的内容规则（按节点值类型区分）：
 *
 *         a) 值类型为数字（int / float）：
 *            内容为数字字面量的完整字符序列。
 *            示例：源文件 `a = 123.45` 中，节点 a 的 RawText
 *            为 "123.45"。
 *
 *         b) 值类型为字符串（string）：
 *            内容为包含外围双引号的完整字符串。
 *            示例：源文件 `a = "hello world"` 中，节点 a 的
 *            RawText 为 "\"hello world\""。
 *
 *         c) 值类型为常量引用（ConstantValue）：
 *            内容为包含 '@' 前缀的完整标记序列。
 *            示例：源文件 `a = @foo` 中，节点 a 的 RawText
 *            为 "@foo"。
 *            示例：源文件 `a = @[foo + 1]` 中，节点 a 的
 *            RawText 为 "@[foo + 1]"。
 *
 *         d) 值类型为未加引号标识符（Ident）：
 *            内容为标识符的完整字符序列。
 *            示例：源文件 `a = some_value` 中，节点 a 的
 *            RawText 为 "some_value"。
 *
 *         此字段的优先级规则：
 *         在序列化阶段（阶段 5），若 RawText 不为 null，则
 *         序列化器必须优先使用 RawText 生成输出文本，忽略
 *         Value 字段的内容。仅当 RawText 为 null 时，序列化器
 *         才回退到使用 Value 和 IsQuoted 生成输出。
 *
 *         此字段的不变性规则：
 *         在阶段 3（常量求值）中，求值器严禁修改任何节点的
 *         RawText 字段。求值操作仅更新 Value 属性。
 *
 *         此字段的 CRUD 规则：
 *         在阶段 4 中，当上层通过 UpdateConfigNode 更新节点时，
 *         若传入的新节点中 RawText 非 null，则目标节点的
 *         RawText 被覆盖为新值。若传入的新节点中 RawText 为
 *         null，则目标节点的 RawText 保持不变（保留原值）。
 *
 * 1.3 原始布局枚举（OriginalLayout）
 *     枚举值：
 *       - Unknown   ：新生成的节点，无原始布局信息。
 *       - SingleLine：节点在源文件中表现为单行。
 *       - MultiLine ：节点在源文件中表现为多行。
 *
 *     此枚举仅作为序列化时的参考提示。实际输出格式由序列化器
 *     根据内容宽度和子节点数量动态计算（见第七章）。
 *
 * 1.4 常量值结构体（ConstantValue）
 *     表示一个尚未求值的常量引用。此结构体在词法分析阶段构建，
 *     在语法分析阶段存入 AstNode.Value，在阶段 3 被求值替换。
 *
 *     字段定义：
 *       - Type (ConstantType)      ：常量引用类型（Simple 或 Expression）。
 *       - Name (string?)           ：若 Type 为 Simple，此字段存储
 *                                    常量名称（不含 '@' 前缀）。
 *       - Text (string?)           ：若 Type 为 Expression，此字段
 *                                    存储方括号内的表达式文本。
 *
 *     此结构体不包含任何求值逻辑，仅作为数据载体。
 *
 * 1.5 节点克隆规则
 *     任何克隆 AST 节点的操作（包括但不限于深拷贝、内联脚本展开
 *     中的节点复制、CRUD 操作中的节点复制）必须满足以下要求：
 *
 *       - 递归复制所有子节点（Children 列表）。
 *       - 复制所有关联注释（AssociatedComments 列表）。
 *       - 复制全部元数据字段（StartLine、EndLine、StartColumn、
 *         EndColumn、IndentWidth、OriginalLayout、SeparatorType）。
 *       - 复制 Value 字段（若为引用类型，需要深拷贝；值类型
 *         直接复制）。
 *       - 复制 RawText 字段（若为非 null，按原样复制字符串）。
 *       - 复制 IsQuoted 字段。
 *
 *     任何克隆实现若遗漏 RawText 字段的复制，均会导致序列化
 *     输出与预期不符，视为严重缺陷。
 *
 *
 * 第二章：词法分析器（Lexer）规范
 * ================================
 *
 * 2.1 常量标记的识别规则
 *     当词法分析器在输入流中遇到 '@' 字符时，必须按以下顺序
 *     尝试匹配常量标记：
 *
 *     步骤 1：检查 '@' 后是否紧跟 '[' 字符。
 *            若是，则进入表达式常量扫描模式。
 *            若不是，则进入简单常量扫描模式。
 *
 *     步骤 2（表达式常量模式）：
 *           a) 读取 '@[' 后的所有字符，直到遇到匹配的 ']'。
 *           b) 方括号必须成对出现（嵌套方括号按深度计数）。
 *           c) 若遇到文件结尾仍未找到匹配的 ']'，生成 Error Token。
 *           d) 若方括号内包含换行符或回车符，生成 Error Token。
 *           e) 若方括号内包含嵌套的 '@[' 序列，生成 Error Token
 *              （禁止嵌套）。
 *           f) 若扫描成功，生成 TokenType.Constant，Value 为
 *              ConstantValue { Type = Expression, Text = 括号内文本 }。
 *
 *     步骤 3（简单常量模式）：
 *           a) 读取 '@' 后的连续字符，直到遇到非法字符或空白。
 *           b) 合法字符集与标识符字符集相同（见 2.3）。
 *           c) 若 '@' 后没有任何合法字符，生成 Error Token。
 *           d) 若扫描成功，生成 TokenType.Constant，Value 为
 *              ConstantValue { Type = Simple, Name = 名称 }。
 *
 * 2.2 原始文本的记录规则
 *     词法分析器在识别任何 Token 时，必须记录该 Token 在输入流
 *     中对应的完整字符范围（起始位置和结束位置）。
 *
 *     在语法分析阶段构建 Simple 节点时，解析器必须从词法分析器
 *     请求该节点对应的完整原始字符序列（从起始位置到结束位置
 *     的所有字符），并直接赋值给 AstNode.RawText。
 *
 *     此记录操作的执行时机：
 *       - 对于 Number 类型 Token：记录数字的完整字符序列。
 *       - 对于 String 类型 Token：记录包含首尾双引号的完整序列。
 *       - 对于 Constant 类型 Token：记录从 '@' 开始的完整序列
 *         （包括方括号及其内部全部内容）。
 *       - 对于 Ident 类型 Token：记录标识符的完整字符序列。
 *
 *     词法分析器不应对 RawText 进行任何修剪、转义或格式化。
 *     RawText 必须是源文件中对应位置的精确子字符串。
 *
 * 2.2-a Token 位置字段定义
 *     Token 必须携带两个只读整数属性，记录其在输入文本中的绝对字符位置：
 *       - StartIndex (int)：Token 第一个字符在输入文本中的索引（从 0 开始，含）。
 *       - EndIndex (int)  ：Token 最后一个字符之后的索引（不含）。
 *     原始文本提取规则：rawText = text.Substring(StartIndex, EndIndex - StartIndex)。
 *     满足以下条件之一时，解析器不得填充 RawText（保持 null）：
 *       - 解析器未持有原始文本（sourceText 为 null）；
 *       - StartIndex < 0 或 EndIndex < StartIndex 或 EndIndex > text.Length。
 *     各 Token 类型的完整字符范围：
 *       - String：包含首尾双引号的完整序列（起始索引在开头引号处，结束索引在结尾引号之后）。
 *       - Constant：从 '@' 开始的完整序列，表达式常量包含方括号及内部全部字符（含内部空格）。
 *       - Number / Ident：字面量的完整字符序列。
 *       - Comment：包含 '#' 及其后全部注释内容的序列。
 *
 * 2.2-b 字符串扫描规则（用户实测原版确认——两种解析规则不同，互不干扰）
 *     **通用代码文件（.txt/.gfx/.gui/.asset）——相邻双引号配对**：
 *     字符串从第一个 '"' 读到**下一个** '"' 即终止（相邻配对，非贪婪）。
 *     引号内除**双引号和回车**外一切字符合法（'#'、'	'、空格、'=' 等）。
 *     回车（''/'
'）也终止（未闭合 → Error Token，描述含起始行号，跳该行剩余）。
 *     例：`from = "07" to = "03"` → **两个独立 Simple**（原版 static_galaxy_example
 *     add_hyperlane 同行为多赋值——用户实测原版确认，严禁改回贪婪合并）。
 *
 *     **本地化 yml（LocalisationParser）——行贪婪**：
 *     值 = 冒号后第一个 '"' 到**该行最后一个 '"'**（LastIndexOf）之间的内容。
 *     不走 Lexer，与通用代码文件规则互不干扰。
 *
 *     推论：
 *       - 通用代码文件：字符串内容中的 '#' 属于字符串内容，不触发注释识别；
 *         '=' 属于字符串内容，不触发分隔符识别。
 *       - 本地化 yml：值可含 '#'、'=' 等（行贪婪，到行尾最后一个引号）。
 *
 *     权威依据：相邻配对为对游戏引擎（Stellaris 本体）解析行为的黑盒测试结果
 *     （用户实测），优先级高于任何对"贪婪合并"的直觉推断。历史版本曾误用
 *     贪婪匹配（同行多个引号对被合并为一个字符串），已废弃。
 *
 * 2.2-c 常量标记的键文本还原规则
 *     当 Constant Token 作为语句的键（如 `@NAME = VALUE`）时，解析器
 *     必须从 ConstantValue 结构还原键文本，严禁使用 ConstantValue.ToString()：
 *       - Type = Simple 且 Name 非空 → 键为 "@" + Name。
 *       - Type = Expression 且 Text 非空 → 键为 "@[" + Text + "]"。
 *     此规则同时适用于顶层语句与块内键值对。
 *
 * 2.3 标识符字符集定义
 *     标识符由以下字符组成：
 *       - 字母：A-Z、a-z（所有 Unicode 字母类别）。
 *       - 数字：0-9（但数字不能作为标识符的第一个字符）。
 *       - 下划线：'_'。
 *       - 连字符：'-'（允许出现在标识符内部，但不能作为第一个
 *         字符）。
 *       - 中文字符及其它 Unicode 表意文字（CJK 统一表意文字）。
 *
 *     非法字符（禁止出现在标识符中）：
 *       - 空字符 '\0'
 *       - 回车 '\r'
 *       - 换行 '\n'
 *       - 制表符 '\t'
 *       - 双引号 '"'
 *       - 井号 '#'
 *       - 等号 '='
 *       - 左大括号 '{'
 *       - 右大括号 '}'
 *       - 左方括号 '['
 *       - 右方括号 ']'
 *       - 左圆括号 '('
 *       - 右圆括号 ')'
 *       - 小于号 '<'
 *       - 大于号 '>'
 *
 * 2.4 错误恢复机制
 *     当词法分析器遇到无法匹配任何 Token 类型的字符序列时，
 *     必须执行以下错误恢复流程：
 *
 *       1. 从当前位置开始，连续扫描所有非法字符（不属于任何
 *          合法 Token 类别的字符）。
 *       2. 记录整个非法序列的起始行号、列号和内容。
 *       3. 生成一个 Error Token，其 Value 为非法序列的描述。
 *       4. 将扫描位置移动到非法序列之后，继续解析。
 *
 *     此机制确保单个非法字符不会导致整个文件解析中断。
 *
 *
 * 第三章：语法分析器（Parser）规范
 * ================================
 *
 * 3.1 AST 构建时的 RawText 赋值规则
 *     在构建每个 Simple 类型节点时，语法分析器必须执行以下操作：
 *
 *       1. 从词法分析器获取当前 Token 的原始字符范围。
 *       2. 从输入源中提取该范围内的子字符串。
 *       3. 将提取的子字符串赋值给新节点的 RawText 属性。
 *
 *     此操作适用于所有 Simple 节点，无论其值类型为 Number、
 *     String、Constant 还是 Ident，均一视同仁。
 *
 *     对于 Block、List、InlineScript 类型节点，其 RawText 属性
 *     必须保持为 null。
 *
 * 3.2 常量声明语句的解析规则
 *     形如 `@NAME = VALUE` 的语句在 AST 中表示为标准的 Simple 节点：
 *       - Key = "@NAME"（包含 '@' 前缀）
 *       - Value = 解析后的 VALUE
 *       - RawText = "Value"（仅值部分）
 *
 *     在阶段 1（全局常量收集）中，解析器通过检查 Key 是否以 '@'
 *     开头来识别常量声明语句。
 *
 * 3.3 块与列表的判定规则
 *     当解析器遇到 '{' 时，按以下规则判定容器类型：
 *
 *       1. 默认将该容器视为 Block。
 *       2. 扫描容器内的所有直接子节点：
 *          a) 若所有子节点均为 Simple 节点且 Key 均为 null，
 *             则将该容器重新判定为 List。
 *          b) 若存在任何 Simple 节点的 Key 不为 null，或存在
 *             任何 Block/List 嵌套结构，则保持为 Block。
 *          c) 若容器内同时包含有键 Simple 节点和无键 Simple
 *             节点，视为混合结构错误，记录错误并跳过。
 *
 *     此判定在解析完成后执行，不影响解析过程中的节点存储。
 *
 * 3.3-a 通用性原则（禁止键名特判）
 *     语法分析器必须是**通用解析器**：严禁按具体键名（如 "inline_script"、
 *     "setup_scenario" 等）识别任何特殊节点类型或改变解析行为。
 *     所有基于键名的语义识别（内联脚本展开、场景解析等）必须由**引擎层**
 *     完成。黑箱游戏引擎唯一支持的内联脚本键名为 "inline_script"
 *     （该名称由游戏引擎固定，不可更改），但此识别属于引擎层
 *     （ScriptExpander）职责：解析器将内联脚本块解析为普通 Block，
 *     ScriptExpander 再按键名识别并展开。
 *
 * 3.4 顶层块与嵌套块入树规则
 *     解析器将块（Block/List/InlineScript）作为语句值时必须将其加入 AST：
 *       - 顶层语句 `key = { ... }`：ParseValueAssignment 在完成
 *         ParseBlockOrList 后，必须将返回的块节点加入当前根节点列表
 *         （AddNode），并将 _lastStatementNode 指向该块节点，以便后续
 *         注释关联。禁止丢弃返回值。
 *       - 块内嵌套块 `innerKey = { ... }`：解析出的嵌套块必须加入
 *         父块节点的 Children 列表（children.Add）。
 *     任何遗漏上述入树操作的实现均会导致顶层块丢失，视为严重缺陷。
 *
 * 3.5 语句完整性规则（分隔符与值约束）
 *       - 键与分隔符必须位于同一行，否则记录错误并跳过该语句。
 *       - 常量声明键（以 '@' 开头）只允许 '=' 分隔符。
 *       - 非 '=' 分隔符（>、<、>=、<=）后禁止双引号字符串。
 *       - 值必须与分隔符位于同一行（块/列表除外，其允许换行）。
 *       - 键、分隔符、值的行一致性违反时，跳过对应 token 并记录 ErrorEntry。
 *
 * 3.6 注释关联规则
 *       - 与上一语句节点同行的注释关联到该节点（内联注释）。
 *       - 语句之间的注释进入待关联队列，在下一语句节点创建时关联到该节点。
 *       - 块结束前仍有待关联注释时，关联到该块节点。
 *       - 解析结束时仍有待关联注释时，关联到最后一个语句节点。
 *
 *
 * 第四章：常量系统架构
 * ====================
 *
 * 4.1 常量存储容器定义
 *
 *     4.1.1 局部常量表（Local Constant Table）
 *           - 数据结构：Dictionary<string, object>
 *           - 作用域：单个文件（.txt/.gfx/.gui/.asset）。
 *           - 生命周期：在阶段 3 的常量求值开始时创建，该文件
 *             的求值完成后立即丢弃。
 *           - 填充来源：文件中所有 Key 以 '@' 开头的 Simple 节点。
 *           - 查找优先级：局部常量表优先于全局常量表。
 *           - 并发规则：同一时间仅处理一个文件，无需加锁。
 *
 *     4.1.2 全局常量表（Global Constant Table）
 *           - 数据结构：Dictionary<string, object>
 *           - 作用域：所有已加载的文件（跨所有根目录）。
 *           - 生命周期：在阶段 0 创建，常驻内存直至调用 Rescan
 *             或显式重置。
 *           - 填充来源：阶段 1 中遍历所有根目录下的
 *             common/scripted_variables/*.txt 文件。
 *           - 合并规则：按根目录优先级从低到高依次合并，后加载
 *             的覆盖先加载的同名常量。
 *           - 访问权限：必须对外公开查询接口（GetGlobalConstant）
 *             和修改接口（SetGlobalConstant）。
 *           - 线程安全：所有访问和修改操作必须由适配器层面的锁
 *             保护（lock (_stateLock)）。
 *
 *     4.1.3 常量引用索引（Constant Reference Index）
 *           - 数据结构：
 *             Dictionary<string, HashSet<WeakReference<AstNode>>>
 *           - 键：全局常量名称（不含 '@' 前缀）。
 *           - 值：一组弱引用，指向 AST 中引用了该常量的节点。
 *           - 作用域：全局，覆盖所有已加载文件的所有 AST。
 *           - 生命周期：在阶段 3 开始时全量构建，运行时通过
 *             CRUD 操作增量维护。
 *           - 访问权限：对外只读可见（提供查询某常量被哪些节点
 *             引用的接口），但修改必须由适配器内部控制。
 *
 * 4.2 常量引用索引的全量构建算法
 *     此算法在阶段 3 开始时执行，构建完整的常量引用索引。
 *
 *     输入：所有已加载文件的 ParserResult 集合。
 *
 *     算法步骤：
 *       1. 创建空的全局索引字典。
 *       2. 遍历每个文件的 ParserResult.RootNodes。
 *       3. 对每个节点执行递归遍历（深度优先）：
 *          a) 若当前节点为 Simple 类型：
 *             i)  检查节点的 RawText 是否包含常量引用模式。
 *             ii) 检查节点的 Value 是否为 ConstantValue 类型。
 *             iii)若检测到常量引用，提取常量名称（Simple 类型
 *                 从 ConstantValue.Name 获取，Expression 类型
 *                 从 RawText 或 Value 中解析出引用的常量名）。
 *             iv) 将当前节点的弱引用加入对应常量名的集合。
 *          b) 若当前节点为 Block、List 或 InlineScript：
 *             递归遍历其 Children。
 *       4. 索引构建完成后，记录 Debug 级别日志，包含索引覆盖
 *          的节点总数和常量总数。
 *
 *     复杂度要求：O(N)，其中 N 为所有 AST 节点的总数。
 *
 * 4.3 常量引用索引的增量维护算法
 *     此算法在 CRUD 操作（AddConfigNode、UpdateConfigNode、
 *     RemoveConfigNode）完成后执行，确保索引与 AST 状态同步。
 *
 *     前置条件：操作已完成对 AST 的修改，但尚未更新索引。
 *
 *     算法步骤（以 UpdateConfigNode 为例）：
 *
 *       步骤 1（移除旧引用）：
 *           a) 若操作涉及修改一个已存在的节点，获取该节点的
 *              旧状态（修改前的值）。
 *           b) 若旧值包含常量引用，提取所引用的常量名称列表。
 *           c) 对每个常量名，从对应的 HashSet 中移除该节点的
 *              弱引用（若存在）。
 *           d) 若移除后 HashSet 为空，可保留空集合或删除该键
 *              （推荐保留空集合以降低开销）。
 *
 *       步骤 2（添加新引用）：
 *           a) 检查修改后节点的新状态是否包含常量引用。
 *           b) 若包含，提取所引用的常量名称列表。
 *           c) 对每个常量名，将当前节点的弱引用加入对应的
 *              HashSet 中。
 *           d) 若该常量名对应的键不存在，则创建新的 HashSet。
 *
 *       步骤 3（新增节点场景）：
 *           a) 直接执行步骤 2（无旧引用可移除）。
 *
 *       步骤 4（删除节点场景）：
 *           a) 获取被删除节点的值，提取其中引用的常量名。
 *           b) 对每个常量名，从对应的 HashSet 中移除该节点的
 *              弱引用。
 *           c) 若 HashSet 变空，保留空集合或删除键。
 *
 *     复杂度要求：O(K + M)，其中 K 为常量引用数量，M 为受影响的
 *     常量数量。
 *
 * 4.4 全局常量修改的联动传播算法
 *     此算法在 SetGlobalConstant 被调用时执行，将常量值的变更
 *     传播到所有引用该常量的 AST 节点。
 *
 *     输入：常量名称（constName）和新值（newValue）。
 *
 *     算法步骤：
 *       1. 更新全局常量表：_globalResolver[constName] = newValue。
 *       2. 从常量引用索引中查找 constName 对应的节点集合。
 *       3. 若未找到任何引用，记录 Information 级别日志：
 *          "常量 {constName} 已更新，但未找到任何活跃引用节点"。
 *          算法结束。
 *       4. 若找到引用集合，遍历该集合中的每个弱引用：
 *          a) 尝试获取 Target（AstNode 实例）。
 *          b) 若 Target 为 null（节点已被垃圾回收），从集合中
 *             移除该弱引用，记录 Debug 级别日志。
 *          c) 若 Target 有效，检查该节点是否仍存在于某个文件的
 *             AST 树中（通过适配器的内部查找机制验证）。
 *          d) 若节点已不在任何树中，从集合中移除该弱引用，
 *             记录 Debug 级别日志。
 *          e) 若节点有效且仍存在于 AST 中，调用 ExpressionEvaluator
 *             针对该节点重新执行求值（仅更新其 Value 字段）。
 *             严禁修改 RawText 字段。
 *       5. 记录 Information 级别日志：
 *          "常量 {constName} 已更新为 {newValue}，共更新
 *          {有效节点数} 个引用节点"。
 *
 *     异常处理：
 *       - 若求值过程中抛出异常，捕获并记录 Error 日志，
 *         继续处理下一个节点，不中断整个传播流程。
 *
 * 4.5 常量引用索引的惰性清理机制
 *     在以下场景中，引擎应对索引执行惰性清理：
 *
 *       1. 每次执行常量传播时（见 4.4），在遍历过程中自动清理
 *          已失效的弱引用。
 *       2. 每次执行 CRUD 操作的增量维护时（见 4.3），自动移除
 *          已不再存在的节点引用。
 *       3. 适配器可通过公开方法 CleanConstantIndex() 手动触发
 *          全量清理：遍历索引中的所有条目，移除所有 Target 为
 *          null 或节点已不在 AST 中的弱引用。
 *
 *     清理操作的日志级别为 Debug。
 *
 *
 * 第五章：解析流程阶段 1（扫描与加载）
 * ====================================
 *
 * 5.1 文件发现规则
 *     扫描所有根目录下的文件，按以下规则筛选：
 *
 *       - 文件扩展名必须在 FileExtensions 列表中（默认包含
 *         .txt、.gui、.gfx、.asset）。
 *       - 忽略所有以 '.' 开头的隐藏文件。
 *       - 递归扫描所有子目录。
 *       - 对于同一相对路径出现在多个根目录的情况，仅保留
 *         最高优先级根目录中的文件（由 _fileIndex 记录）。
 *
 * 5.1-a 相对路径规范化（NormalizePath）
 *     适配器内部所有相对路径必须使用正斜杠 '/' 作为目录分隔符。
 *     扫描阶段生成的文件相对路径（由 Path.GetRelativePath 产生，
 *     在 Windows 上使用反斜杠）必须经 NormalizePath 规范化：
 *       - 将 '\' 替换为 '/'；
 *       - 去除开头的 '/'；
 *       - 去除结尾的 '/'。
 *     规范化应用于：
 *       - _configResults / _configRoots / _fileIndex 的键；
 *       - 本地化路径（localisation/{lang}/{file}）；
 *       - CRUD 接口（AddConfigNode、UpdateConfigNode、RemoveConfigNode）
 *         的 relativePath 参数。
 *     违反此规则会导致同一文件以正斜杠与反斜杠两种键同时存在，
 *     查询与 CRUD 失效，视为严重缺陷。
 *
 * 5.1-b 内联脚本解析的原始文本
 *     ScriptExpander 对内联脚本内容执行词法分析后，必须将替换后的
 *     完整内容作为原始文本传入 Parser，使展开出的节点正确填充 RawText。
 *
 * 5.2 全局常量加载规则
 *     在文件发现阶段结束后，执行全局常量加载：
 *
 *       1. 按根目录优先级从低到高遍历每个根目录。
 *       2. 对每个根目录，遍历 common/scripted_variables/ 下的
 *          所有 .txt 文件（按文件名升序排序）。
 *       3. 对每个 .txt 文件，执行完整的词法分析和语法分析，
 *          生成 ParserResult。
 *       4. 遍历 ParserResult.RootNodes，识别 Key 以 '@' 开头且
 *          Type 为 Simple 的节点。
 *       5. 提取常量名称（Key 去除 '@' 前缀）和值（Value 字段）。
 *       6. 若值是数字字面量（int、long、float、double），
 *          存入全局常量表。
 *       7. 若值不是数字字面量，记录 Error 日志并跳过该常量定义。
 *
 *     全局常量表的合并规则：
 *       - 按根目录遍历顺序依次写入。
 *       - 若新常量已存在于表中，用新值覆盖旧值（高优先级覆盖
 *         低优先级）。
 *       - 低优先级根目录中的独有常量保留。
 *
 * 5.3 局部常量收集规则
 *     在解析每个 .txt 文件时，并行执行局部常量收集：
 *
 *       1. 创建该文件专属的临时局部常量表。
 *       2. 遍历文件的 ParserResult.RootNodes。
 *       3. 识别 Key 以 '@' 开头且 Type 为 Simple 的节点。
 *       4. 提取常量名称和值，存入局部常量表。
 *       5. 解析顺序：按 AST 顺序依次处理，后定义的覆盖
 *          先定义的同名常量。
 *
 *     局部常量表的作用域仅限于当前文件，解析完成后即丢弃。
 *
 *
 * 第六章：解析流程阶段 3（常量求值）
 * ==================================
 *
 * 6.1 求值顺序规范
 *
 *       步骤 1：构建该文件的局部常量表（见 5.3）。
 *
 *       步骤 2：遍历该文件的 AST，对所有 Simple 节点执行求值：
 *               - 检查节点的 Value 是否为 ConstantValue 类型。
 *               - 若是，根据 ConstantValue.Type 执行相应求值。
 *
 *       步骤 3：求值完成后，丢弃局部常量表。
 *
 *       步骤 4：所有文件处理完成后，常量引用索引已全量构建。
 *
 *     此顺序确保在求值任何节点之前，该文件的所有局部常量已
 *     被收集完毕。
 *
 * 6.2 简单常量求值规则（@var）
 *     对 ConstantValue { Type = Simple, Name = "foo" } 执行求值：
 *
 *       1. 查找局部常量表，若存在键 "foo"，则返回对应的 Value。
 *       2. 若局部不存在，查找全局常量表，若存在键 "foo"，
 *          则返回对应的 Value。
 *       3. 若全局也不存在，保留原 ConstantValue 不变（不替换）。
 *       4. 记录 Warning 日志："未找到常量: @{Name}"。
 *
 *     求值结果写入节点的 Value 字段。
 *     节点的 RawText 字段保持不变。
 *
 * 6.3 表达式常量求值规则（@[expr]）
 *     对 ConstantValue { Type = Expression, Text = "foo + 1" }
 *     执行求值：
 *
 *       步骤 1：提取方括号内的表达式文本（如 "foo + 1"）。
 *
 *       步骤 2：在表达式文本中查找所有裸标识符（如 "foo"）。
 *               对每个裸标识符执行常量查找（局部优先于全局）。
 *               将找到的值替换到表达式中（数字替换为数字字面量，
 *               字符串替换为带引号的字符串）。
 *
 *       步骤 3：对替换后的表达式字符串进行算术求值。
 *               支持的操作符：+、-、*、/、()。
 *               求值顺序：括号优先，乘除优先于加减。
 *
 *       步骤 4：若求值结果为整数（double 与整数差值 < 1e-9），
 *               转换为 int 类型；否则保留为 double。
 *
 *       步骤 5：若求值过程中出现除零错误或解析错误，捕获异常，
 *               记录 Error 日志，保留原 ConstantValue 不变。
 *
 *       步骤 6：将求值结果写入节点的 Value 字段。
 *               节点的 RawText 字段保持不变。
 *
 * 6.4 表达式中的非法字符检测
 *     在表达式求值之前，必须检测表达式文本是否包含以下非法
 *     字符：{、}、#、=、"、'。
 *     若包含，记录 Error 日志，不执行求值，保留原值。
 *
 * 6.5 表达式中的嵌套限制
 *     表达式文本中禁止出现嵌套的 '@[' 序列。
 *     若检测到嵌套，记录 Error 日志，不执行求值，保留原值。
 *
 *
 * 第七章：序列化与写回规则（SerializationHelper）
 * ================================================
 *
 * 7.1 值的输出优先级规则
 *     在序列化 Simple 类型节点时，按以下优先级决定输出的
 *     文本内容：
 *
 *       优先级 1（最高）：若节点的 RawText 不为 null，
 *                         则直接输出 RawText 的内容。
 *                         此规则适用于所有情况，无论 RawText
 *                         的内容是否与 Value 一致。
 *
 *       优先级 2：若 RawText 为 null，则使用 FormatValue(Value,
 *                 IsQuoted) 生成输出文本。
 *
 *     此优先级规则确保：只要节点在解析或 CRUD 操作中保留了
 *     原始文本，写回磁盘时即可完全还原原始写法（包括宏引用、
 *     表达式、特殊空格等）。
 *
 * 7.2 注释的序列化规则
 *     注释节点不单独输出，而是通过 AssociatedComments 列表
 *     关联到所属的语句节点。
 *
 *     序列化顺序：
 *       1. 在输出关联的语句节点之前，先输出 AssociatedComments
 *          中的所有注释节点（按列表顺序）。
 *       2. 每个注释节点输出为 '#{Comment.Value}'，缩进层级与
 *          关联节点相同。
 *       3. 注释与后续语句之间保留一个换行。
 *
 * 7.3 块与列表的单行/多行判定规则
 *     在序列化 Block 和 List 时，根据以下规则决定输出为单行
 *     还是多行：
 *
 *       规则 1（强制单行）：
 *         若内容总宽度（不含缩进）<= 64 字符，强制单行输出。
 *         宽度计算规则：制表符按 4 字符，汉字按 2 字符，
 *         其他字符按 1 字符。
 *
 *       规则 2（强制多行）：
 *         若内容总宽度 > 64 字符 且（子节点数量 >= 3 或
 *         嵌套深度 >= 2），强制多行输出。
 *
 *       规则 3（默认）：
 *         若上述规则均不触发，按原始布局 OriginalLayout 提示
 *         输出（SingleLine 为单行，MultiLine 为多行）。
 *
 * 7.4 原子写入规则
 *     所有写回磁盘的操作必须遵循以下原子写入流程：
 *
 *       1. 生成完整的目标文件路径（由目标根目录 + 相对路径
 *          组成）。
 *       2. 生成临时文件路径：目标路径 + ".temp"。
 *       3. 将序列化内容写入临时文件。
 *       4. 若写入过程中发生异常，删除临时文件，抛出异常。
 *       5. 若写入成功，检查目标文件是否存在，若存在则删除。
 *       6. 将临时文件重命名为目标文件路径。
 *       7. 若重命名过程中发生异常，删除临时文件，抛出异常。
 *
 *     此流程确保在任何故障情况下，不会留下损坏的目标文件。
 *
 *
 * 第八章：适配器内存 CRUD 接口规范
 * ================================
 *
 * 8.1 AddConfigNode 的节点构造约定
 *     上层调用 AddConfigNode 时，传入的 AstNode 实例允许
 *     填充 RawText 字段。适配器在克隆节点时，必须保留
 *     RawText 内容。
 *
 *     若传入的节点中 RawText 为 null，适配器不应自动生成
 *     RawText（仅解析器有权填充 RawText）。
 *
 * 8.2 UpdateConfigNode 的 RawText 处理规则
 *     UpdateConfigNode 执行时，按以下规则处理 RawText：
 *
 *       - 若传入的新节点中 RawText 非 null，则将目标节点的
 *         RawText 覆盖为新值。
 *       - 若传入的新节点中 RawText 为 null，则目标节点的
 *         RawText 保持不变（不覆盖）。
 *       - 若传入的新节点中 Value 改变但 RawText 保留原值，
 *         则目标节点的 RawText 也保留原值（即 Value 改变
 *         不影响 RawText）。
 *
 * 8.3 RemoveConfigNode 的索引清理规则
 *     RemoveConfigNode 删除节点后，必须执行以下清理：
 *
 *       1. 获取被删除节点的 Value 和 RawText。
 *       2. 检测其中是否包含常量引用。
 *       3. 若包含，从常量引用索引中移除该节点的所有弱引用。
 *       4. 若索引中的对应集合变为空，保留空集合（不删除键）。
 *
 * 8.4 常量引用索引的增量维护触发点
 *     以下 CRUD 操作完成后，必须调用常量引用索引的增量维护
 *     算法（见 4.3）：
 *
 *       - AddConfigNode（新增节点）。
 *       - UpdateConfigNode（修改节点）。
 *       - RemoveConfigNode（删除节点）。
 *
 *     维护操作的执行时机：在 CRUD 操作完成、状态锁释放之前。
 *
 *
 * 第九章：重扫描（Rescan）的状态重置规范
 * ======================================
 *
 * 9.1 必须清空的全部状态列表
 *     调用 Rescan 时，以下状态必须被完全清空或重置：
 *
 *       - _configResults：所有文件的 ParserResult 缓存。
 *       - _configRoots：所有文件与根目录的映射。
 *       - _localisationTable：所有语言的本地化数据。
 *       - _csvCache：所有目录的 CSV 合并缓存。
 *       - _globalResolver：全局常量表（全量清空）。
 *       - _constantReferenceIndex：常量引用索引（全量清空）。
 *       - _expander：内联脚本展开器的缓存状态。
 *       - _fileIndex：文件系统索引（全量清空）。
 *
 * 9.2 重建顺序
 *     清空完成后，必须按以下顺序重建所有状态：
 *
 *       1. 阶段 0：重新初始化空的全局常量表和常量引用索引。
 *       2. 阶段 1：重新执行文件发现、解析、常量收集。
 *       3. 阶段 2：重新执行内联脚本展开。
 *       4. 阶段 3：重新执行常量求值和索引构建。
 *
 *     此顺序与首次 ScanAll 完全一致，确保 Rescan 后的状态
 *     与 ScanAll 后的状态等价。
 *
 * 9.3 日志保留规则
 *     Rescan 不得清空日志文件或重置日志系统。
 *     所有 Rescan 过程中的日志必须追加到现有日志文件。
 *
 *
 * 第十章：全局常量表的对外接口规范
 * ================================
 *
 * 10.1 查询接口（GetGlobalConstant）
 *     签名：object? GetGlobalConstant(string name)
 *
 *     行为：
 *       1. 若 name 为空，抛出 ArgumentException。
 *       2. 在全局常量表中查找键为 name 的条目。
 *       3. 若存在，返回对应的 Value。
 *       4. 若不存在，返回 null（不抛出异常）。
 *
 *     线程安全：此方法必须加锁保护。
 *
 * 10.2 修改接口（SetGlobalConstant）
 *     签名：void SetGlobalConstant(string name, object value)
 *
 *     行为：
 *       1. 若 name 为空或 value 为 null，抛出 ArgumentException。
 *       2. 若 value 不是数字类型（int、long、float、double），
 *          抛出 ArgumentException。
 *       3. 更新全局常量表中的条目。
 *       4. 触发常量传播算法（见 4.4）。
 *       5. 记录 Information 级别日志。
 *
 *     线程安全：此方法必须加锁保护。
 *
 * 10.3 引用查询接口（GetConstantReferences）
 *     签名：IReadOnlyList<AstNode>? GetConstantReferences(string name)
 *
 *     行为：
 *       1. 若 name 为空，抛出 ArgumentException。
 *       2. 从常量引用索引中查找键为 name 的集合。
 *       3. 若不存在，返回 null。
 *       4. 若存在，遍历集合中的弱引用，收集所有 Target
 *          仍有效的节点，返回只读列表。
 *       5. 在遍历过程中自动清理已失效的弱引用。
 *
 *     线程安全：此方法必须加锁保护。
 *
 * 10.4 常量输入求值接口（ResolveConstantInput）
 *     签名：object? ResolveConstantInput(string? input)
 *
 *     行为：
 *       1. 对 input 执行 Trim；若结果为空，返回 null。
 *       2. 若结果以 '@' 开头：
 *          a) 形如 "@name"（非 "@[" 开头）→ 构造 ConstantValue
 *             { Type = Simple, Name = name }。
 *          b) 形如 "@[expr]"（首尾分别为 '@[' 与 ']'）→ 构造
 *             ConstantValue { Type = Expression, Text = expr }。
 *          c) 使用 ExpressionEvaluator（基于全局常量表）求值。
 *          d) 常量未找到或求值失败时返回 null（不抛异常），
 *             调用方可保留原文写回、交由游戏端解析。
 *       3. 不以 '@' 开头 → 直接返回 Trim 后的字符串原样。
 *     用途：供上层引擎（如 GalaxyStyleEngine）支持常量引用输入。
 *     线程安全：此方法必须加锁保护。
 *
 *
 * 第十一章：配置与开关规范
 * ========================
 *
 * 11.1 文件扩展名列表（FileExtensions）
 *      类型：List<string>
 *      默认值：{ ".txt", ".gui", ".gfx", ".asset" }
 *      用途：阶段 1 文件发现时的扩展名筛选。
 *      修改时机：在调用 ScanAll 或 Rescan 之前修改有效。
 *
 * 11.2 内联脚本开关（EnableInlineScript）
 *      类型：bool
 *      默认值：true
 *      用途：控制是否执行阶段 2 的内联脚本展开。
 *      修改时机：在调用 ScanAll 或 Rescan 之前修改有效。
 *
 * 11.3 CSV 合并开关（EnableCsvMerge）
 *      类型：bool
 *      默认值：true
 *      用途：控制是否在阶段 1 执行 CSV 与块的合并。
 *      修改时机：在调用 ScanAll 或 Rescan 之前修改有效。
 *
 * 11.4 迭代深度配置（MaxIterationDepth）
 *      类型：int
 *      默认值：127
 *      范围：7 ~ 65535
 *      用途：本地化 $var$ 替换和内联脚本展开的最大迭代轮数。
 *      修改时机：运行时任意时刻可修改，立即生效。
