 * 第十二章：错误处理与日志规范
 * ============================
 *
 * 12.1 错误行记录
 *     解析过程中发现的每个语法错误必须被记录为 ErrorEntry：
 *
 *       - Line (int)       ：错误行号（从 1 开始）。
 *       - Column (int)     ：错误列号（从 1 开始）。
 *       - Content (string) ：错误行的原始内容。
 *       - Reason (string)  ：错误原因的描述文本。
 *
 *     错误条目存储在 ParserResult.Errors 列表中。
 *     序列化时，所有错误行被丢弃（不写入输出文件）。
 *
 * 12.2 日志级别规范
 *       - Debug    ：详细的内部状态变化，如索引维护、缓存操作。
 *       - Information：重要的生命周期事件，如扫描开始/完成、
 *                     常量传播成功。
 *       - Warning  ：可恢复的问题，如常量未找到、循环引用检测。
 *       - Error    ：不可恢复的问题，如文件解析失败、求值异常。
 *
 * 12.3 日志实现要求
 *      使用 Microsoft.Extensions.Logging 标准接口。
 *      日志系统支持异步队列写入，避免阻塞主线程。
 *      支持失败重试机制（默认重试 3 次，间隔 100ms）。
