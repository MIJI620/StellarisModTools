/*
 * ============================================================================
 * STELLARIS MOD TOOLS EDITOR STANDARD SPECIFICATION (REVISION 1.0)
 * ============================================================================
 * 本规范为可视化前端（Stellaris.Editor）实现的唯一权威依据。
 * 所有实现必须严格遵循本规范定义的界面结构、初始化流程、本地化机制
 * 与错误处理。本规范在逻辑上优先于任何现有代码实现，实现偏差均视为缺陷。
 * ============================================================================
 *
 *
 * 术语定义
 * --------
 * - 根目录（Root Directory）：模组文件系统的顶层目录路径。用户通过界面
 *   多选添加，列表末尾（索引最大）的目录优先级最高（与 StellarisAdapter
 *   语义一致）。根目录列表是初始化流程的核心输入。
 *
 * - 界面本地化（UI Localisation）：存储于 exe 所在目录 `localisation/`
 *   子目录中的 JSON 键值对集合。主界面与初始化状态浮层的全部可见文本
 *   必须从该模块提取，禁止在 XAML 或代码中硬编码 UI 字符串。
 *
 * - 偏好设置（User Preferences）：存储用户上次使用的根目录列表、界面
 *   语言等持久化信息，存放于 exe 所在目录 `config/user_prefs.json`。
 *
 * - 初始化引导器（Bootstrapper）：应用启动后负责载入本地化、读取偏好、
 *   弹出 Roots 选择、按顺序初始化 StellarisAdapter 与三个引擎、
 *   并以状态浮层实时汇报进度的模块。
 *
 * - 状态汇报浮层（Status Overlay）：初始化期间显示的半透明无边框浮层，
 *   用于向用户展示"正在扫描哪个文件 / 正在初始化哪个引擎"。
 *
 * - 主界面（Main Window）：初始化完成后展示的主窗口，用于操控与编辑
 *   GalaxyStyleEngine（星系样式引擎）与 GalaxyMapEngine（银河地图引擎）。
 *
 *
 * 总体执行顺序（强制，不可调整）
 * ------------------------------
 * 阶段 0（界面本地化载入）：
 *   从 exe 所在目录 `localisation/` 载入全部语言 JSON，确定当前语言。
 * 阶段 1（偏好设置读取）：
 *   从 `config/user_prefs.json` 读取根目录列表与界面语言；缺失或损坏时
 *   回退到空偏好（不崩溃，仅记录警告）。
 * 阶段 2（Roots 选择）：
 *   若偏好中无任何根目录，自动弹出 Roots 文件夹多选界面（模态），
 *   用户确认后写入偏好设置；若已存在根目录则直接进入阶段 3。
 * 阶段 3（SA 初始化）：
 *   按偏好顺序将根目录逐一 AddRoot，随后调用 ScanAll()（全量扫描）。
 * 阶段 4（ImageAssetEngine 初始化）：
 *   以根目录列表构造图像资产引擎。
 * 阶段 5（SpriteManagementEngine 初始化）：
 *   以 SA 与图像引擎构造精灵管理引擎（构建子图形索引）。
 * 阶段 6（GalaxyStyleEngine 初始化）：
 *   构造星系样式引擎（构造函数内部自动 LoadAllStyles）。
 * 阶段 7（GalaxyMapEngine 初始化）：
 *   构造银河地图引擎并调用 ScanAll()。
 * 阶段 8（进入主界面）：
 *   关闭状态浮层，显示主窗口。
 *
 * 阶段 3 ~ 7 执行期间，状态浮层必须持续显示当前正在处理的对象
 * （文件名 / 任务类型），文本取自界面本地化模块。
 *
 *
 * 第一章：技术栈与分层
 * ====================
 *
 * 1.1 技术栈（强制）
 *     - WPF（.NET 10，TargetFramework `net10.0-windows`，UseWPF=true）。
 *     - MVVM：View 层（XAML）与 ViewModel 层分离，绑定使用
 *       CommunityToolkit.Mvvm（ObservableObject / RelayCommand）。
 *     - 唯一入口：App.xaml 的 Application 启动事件中调用初始化引导器。
 *
 * 1.2 分层与依赖方向（强制，不可反向）
 *     View（XAML/Code-behind 仅做视图逻辑）
 *       → ViewModel（界面状态、命令、文本绑定）
 *       → 引擎层（GalaxyStyleEngine / GalaxyMapEngine / ImageAssetEngine /
 *          SpriteManagementEngine，位于 Stellaris.Engine）
 *       → 适配器（Stellaris.Parser.StellarisAdapter）
 *     ViewModel 严禁直接操作磁盘或解析文件；所有文件读写必须经由
 *     StellarisAdapter，所有图像/精灵操作必须经由对应引擎。
 *
 * 1.3 依赖清单（强制）
 *     - Stellaris.Parser（StellarisAdapter、ParserResult 等）
 *     - Stellaris.Engine（GalaxyStyleEngine、GalaxyMapEngine、
 *       ImageAssetEngine、SpriteManagementEngine）
 *     - CommunityToolkit.Mvvm
 *
 * 1.4 线程与 UI 亲和性
 *     - 引擎公开方法内部自带锁，可在 UI 线程直接调用（简单场景）。
 *     - 长耗时操作（扫描、导出、网格/图像生成）通过引擎的
 *       TaskChanged 事件汇报进度；事件回调须经 Dispatcher 切换到
 *       UI 线程后更新界面。
 *     - 初始化阶段必须向用户展示进度，禁止无反馈地阻塞 UI 超过
 *       100ms。
 *
 *
 * 第二章：界面本地化模块（UILocalisationManager）
 * ==============================================
 *
 * 2.1 载入目录与文件格式
 *     - 目录：exe 所在目录下 `localisation/`。
 *     - 文件：每个语言一个 JSON 文件，文件名即语言标识，
 *       如 `en-US.json`、`zh-CN.json`。
 *     - 内容：扁平 JSON 键值对，值必须为字符串（支持 {0} 占位符）。
 *       示例：
 *         { "status.scanning": "正在扫描: {0}",
 *           "main.title": "群星模组工具" }
 *     - 目录不存在或为空：回退到内置默认语言（见 2.4），记录警告。
 *
 * 2.2 公开接口（强制）
 *     - string Get(string key, string? lang = null)
 *         按指定语言（缺省为当前语言）取文本；支持 {0}/{1} 占位，
 *         由调用方 Format 或模块提供 Format(key, params object[])。
 *     - void SetLanguage(string lang)：切换当前语言并持久化到偏好设置。
 *     - string CurrentLanguage { get; }
 *     - IReadOnlyCollection<string> AvailableLanguages { get; }
 *     - event EventHandler? LanguageChanged：语言切换通知
 *       （ViewModel 据此刷新全部文本绑定）。
 *
 * 2.3 使用范围（强制）
 *     - 主界面全部可见文本、状态浮层全部文本、错误提示文本，
 *       一律经此模块提取；XAML 中禁止硬编码中文/英文 UI 字符串。
 *     - 占位符文本（如用户输入的样式名、路径）不属于本地化范围。
 *
 * 2.4 回退规则（防御性，强制）
 *     1) 当前语言 JSON 中存在该键 → 返回该值。
 *     2) 不存在 → 回退默认语言（内置 `en-US`）中的该键。
 *     3) 默认语言也不存在 → 返回键名本身（保证界面永不因缺键崩溃）。
 *     4) JSON 解析失败 → 跳过该语言文件并记录警告，不影响其他语言。
 *
 *
 * 第三章：偏好设置模块（UserPreferences）
 * ======================================
 *
 * 3.1 存储
 *     - 文件：exe 所在目录 `config/user_prefs.json`，原子写入
 *       （临时文件 + 重命名，参考 LocalConfigManager 的写入方式）。
 *     - JSON 结构：
 *         {
 *           "roots": [ "D:/mods/root_a", "D:/mods/root_b" ],
 *           "language": "zh-CN",
 *           "window": { "width": 1280, "height": 800 }
 *         }
 *
 * 3.2 字段
 *     - roots（List<string>）：根目录列表，顺序即优先级（末尾最高）。
 *     - language（string）：界面语言，缺省回退默认语言。
 *     - window：主窗口尺寸（可选，缺省用默认值）。
 *
 * 3.3 防御性（强制）
 *     - 文件缺失 / 损坏 / 含非法路径：整体回退空偏好，记录警告，
 *       绝不崩溃；非法条目（不存在的目录）在 Roots 界面中标记并
 *       允许用户移除。
 *     - 保存失败：记录警告，不影响当前会话。
 *
 *
 * 第四章：初始化引导器（Bootstrapper）
 * ====================================
 *
 * 4.1 职责
 *     负责总体执行顺序阶段 0 ~ 8 的串联，并将进度汇报到状态浮层。
 *
 * 4.2 Roots 多选界面
 *     - 触发条件：偏好设置中无任何有效根目录（阶段 2）。
 *     - 行为：模态多选目录界面；支持添加多个目录并调整顺序
 *       （顺序即优先级，界面须可视化提示"越靠后优先级越高"）。
 *     - 确认后：写入偏好设置并继续初始化；取消则退出应用。
 *     - 若已存在偏好根目录：不弹出，直接进入阶段 3。
 *
 * 4.3 引擎初始化顺序（强制，不可调整）
 *     SA（AddRoot × N → ScanAll）
 *       → ImageAssetEngine
 *       → SpriteManagementEngine（构建子图形索引）
 *       → GalaxyStyleEngine（LoadAllStyles）
 *       → GalaxyMapEngine（ScanAll）
 *     任一步失败：状态浮层显示失败原因（本地化键），提供"重试"与
 *     "取消"；不允许未处理异常导致应用直接退出。
 *
 * 4.4 进度汇报协议
 *     - SA：订阅 StellarisAdapter.TaskChanged（ParserTaskType），
 *       Argument 为文件路径/任务参数 → 显示"正在扫描: {0}"。
 *     - GalaxyStyleEngine：订阅 TaskChanged（EngineTaskType）。
 *     - GalaxyMapEngine：订阅 TaskChanged（GalaxyMapTaskType）；
 *       引擎必须提供该事件（实现时补充）。
 *     - SpriteManagementEngine：若未提供任务事件，则显示静态文本
 *       "正在初始化精灵索引"。
 *     - 所有事件回调经 Dispatcher 切换至 UI 线程更新浮层。
 *
 * 4.5 状态浮层样式（强制）
 *     - 窗口样式：半透明白色背景（约 #CCFFFFFF）、黑色文字、
 *       无边框（WindowStyle=None）、无系统控制按钮（ResizeMode=NoResize、
 *       无最小化/最大化/关闭按钮）、无拖动（固定居中，禁用
 *       DragMove 入口）。
 *     - 尺寸：自适应文本内容，宽高有限制（如最大 420×200）。
 *     - 始终置顶（Topmost=true）直至初始化结束。
 *     - 文本：主状态行 + 可选次级行（当前任务类型）。
 *
 *
 * 第五章：主界面（Main Window）
 * =============================
 *
 * 5.1 整体结构（导航驱动页面 + 分块式布局，强制）
 *     主界面采用"顶部全局工具栏 + 左侧导航 + 右侧**导航驱动的页面容器**"：
 *       - 顶部全局工具栏：保存全部、导出、重扫、语言切换、根目录管理等
 *         跨页面操作（文本均来自界面本地化）。
 *       - 左侧导航：功能页入口（文本来自界面本地化）。
 *       - 右侧内容区：是一个页面容器（ContentControl / Frame），
 *         **切换导航项时内容区整体切换**到对应功能页；每页内部由若干
 *         **功能块（Block/Panel）**组合而成，每块拥有标题栏（可折叠）与
 *         独立内容区，块与块按网格排列。
 *
 *     布局选型理由：后续将扩展至少 7 种新功能，其中既有纯文本输入型、
 *     也有着重图像渲染型与大致图像渲染型；导航驱动页面使各功能彼此
 *     隔离、按需加载，分块式布局允许不同页面自由组合不同块类型。
 *
 * 5.1-a 功能块（Block）类型定义
 *     - ListBlock    ：对象列表（搜索、排序、多选/单选）。
 *     - FormBlock    ：参数表单（分区字段：数值/字符串/常量引用输入）。
 *     - CanvasBlock  ：点阵画布（静态地图星系点 + 航道连线，框选/单点编辑）。
 *     - ImageBlock   ：图像显示（预览图 / 按钮图标）。
 *     - TextBlock    ：纯文本（本地化键值对、日志、说明）。
 *     - MixedBlock   ：混合内容（如 列表 + 预览 联动）。
 *     各功能页按需组合这些块；块内容类型可继续扩充（扩展点）。
 *
 * 5.1-b 三个银河引擎页共享页面模板（强制）
 *     星系样式 / 动态地图 / 静态地图三页必须共享同一套页面骨架：
 *       "对象列表（ListBlock，左）+ 编辑区（FormBlock / 系统表格，中）+
 *        预览区（右）"
 *     三者仅数据源与编辑字段不同，通过参数化模板复用同一 View + ViewModel
 *     基类，禁止为每页复制整套布局代码。
 *
 *     预览区布局规则（强制）：
 *       - **默认置于右侧栏**：横屏（宽窗口）下右侧栏高度充足，绘制区
 *         边长取 min(栏宽, 栏高)，可获得最大的方形绘制区域；底部布局
 *         仅作为可切换的备选（高度受限时方块必然偏小）。
 *       - 绘制控件（形状预览 / 点阵画布）必须保持 **1:1 等比缩放**
 *         （ScaleTransform 保纵横比、内容居中、超出部分留白），
 *         严禁拉伸变形；绘制区尺寸随窗口/分栏变化自适应。
 *       - 预览区与列表/编辑区之间允许分栏拖拽调整宽度。
 *
 * 5.1-c 导航项（初始）
 *       - 星系样式（样式表管理、参数编辑、导出；共享模板：列表 + 表单 + 预览）
 *       - 动态地图（setup_scenario 管理；共享模板：列表 + 表单 + 形状排序）
 *       - 静态地图（static_galaxy_scenario 管理；共享模板：列表 + 系统表格 +
 *         点阵画布 + 工具栏：网格生成/图像转点阵/单点编辑/伪样式导出）
 *       - 本地化（界面语言切换、mod 本地化查看；文本/表格块）
 *       - 设置（根目录管理、重扫；表单块）
 *     新功能 = 新增导航项 + 页内块组合，不修改引导器主流程。
 *
 * 5.2 引擎对接原则
 *     - 所有编辑操作调用引擎公开接口（GalaxyStyleEngine /
 *       GalaxyMapEngine），禁止绕过引擎直接操作 SA 内存或磁盘。
 *     - 长任务（导出、网格生成、图像转点阵）执行时以任务事件或
 *       忙碌指示反馈，禁止界面假死。
 *     - 静态地图的点阵画布必须基于引擎提供的坐标数据绘制
 *       （GetStaticScenario().Systems / Hyperlanes），禁止另起数据源。
 *
 * 5.3 语言切换
 *     切换后经 UILocalisationManager.LanguageChanged 通知刷新
 *     全部 ViewModel 文本绑定，即时生效并持久化。
 *
 *
 * 第六章：错误处理与防御性（强制）
 * ================================
 *
 * 6.1 默认输入不可信
 *     用户可能输入庞大、非法或恶意数据（超长路径、超大数值、损坏文件、
 *     缺失依赖等）。任何异常必须被捕获并转换为用户可读提示，禁止未捕获
 *     异常导致应用崩溃。
 *
 * 6.2 错误呈现
 *     - 初始化错误：状态浮层显示（本地化键 + 异常摘要），可重试。
 *     - 运行期错误：主界面内联提示或对话框，文本经本地化模块。
 *     - 错误日志：文件 + Debug 输出（复用现有日志能力）。
 *
 * 6.3 尽力恢复
 *     单个文件/引擎初始化失败不得中断整体流程（SA 扫描已保证单文件
 *     失败跳过；引擎构造失败按 4.3 处理）。
 *
 * 6.4 空数据与取消
 *     - Roots 为空且用户取消：退出应用。
 *     - 引擎加载 0 个样式/场景：主界面显示空态提示（本地化键），
 *       不视为错误。
 *
 *
 * 第七章：性能与扩展
 * =================
 *
 * 7.1 初始化期间 UI 必须响应（进度事件 + 异步任务），禁止同步阻塞。
 * 7.2 新功能以"导航项 + ViewModel + View"三元组扩展，不修改初始化
 *     引导器主流程。
 * 7.3 界面本地化键采用点分命名（如 main.style、status.scanning），
 *     便于组织与扩展。
 *
 * ============================================================================
 * 规范结束
 * ============================================================================
 */
namespace Stellaris.Editor;
